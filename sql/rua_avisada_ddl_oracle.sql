COMMENT ON COLUMN DIM_SUBPREFEITURA.sk_zona IS 'FK para DIM_ZONA: zona da subprefeitura.';

DROP TABLE DIM_TEMA CASCADE CONSTRAINTS;

CREATE TABLE DIM_TEMA (
    sk_tema  NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nm_tema  VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_DIM_TEMA PRIMARY KEY (sk_tema)
);

COMMENT ON TABLE DIM_TEMA IS 'Tema do SP156 (nível mais alto da hierarquia de serviço).';
