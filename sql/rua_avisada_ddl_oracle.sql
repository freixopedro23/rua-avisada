-- Rua Avisada — Data Warehouse (modelo Snowflake) · DDL para Oracle Database (12c ou superior)
-- Global Solution 2026.2 · FIAP · Data Science · Turma 2TSCOR
-- Grupo Welcome to the DataFrame
--
-- O que este script cria:
--   9 dimensões, 2 fatos e 1 tabela agregada, com chaves primárias (PK),
--   chaves estrangeiras (FK), restrições de domínio (CHECK), índices nas FKs e
--   comentários (COMMENT ON) em todas as tabelas e colunas.
--
-- Padrão de nomes
--   Tabelas em maiúsculas: DIM_ (dimensão), FTO_ (fato) e AGG_ (agregado). Colunas com prefixo do tipo de dado:
--     sk_  chave substituta / chave do modelo     id_  identificador do fato
--     cd_  código                                 nm_  nome
--     ds_  descrição ou texto de domínio          sg_  sigla
--     dt_  data                                   nr_  número (ano, mês, coordenada, índice)
--     qt_  quantidade (contagem)                  vl_  valor medido (mm, km², m, dias, taxas)
--     pc_  percentual                             fl_  indicador (S/N ou 0/1)
--   Os CSVs de data/modelo/ mantêm os nomes originais do pipeline Python; cada
--   COMMENT ON COLUMN informa a coluna correspondente no CSV ("CSV: ...").
--
-- Chaves primárias
--   * GENERATED BY DEFAULT AS IDENTITY nas chaves substitutas sequenciais puras:
--     DIM_STATUS, DIM_TEMA, DIM_ASSUNTO, DIM_SERVICO, DIM_ZONA, DIM_ESTACAO_INMET e
--     FTO_SOLICITACAO. "BY DEFAULT" aceita os números que vêm do ETL na carga e só
--     gera um número quando a linha chega sem chave.
--   * Sem IDENTITY: DIM_DISTRITO e DIM_SUBPREFEITURA (códigos oficiais do GeoSampa),
--     DIM_TEMPO (chave AAAAMMDD), FTO_DISTRITO_DIA (PK composta) e
--     AGG_INDICADORES_DISTRITO (a PK é a própria FK do distrito).
--   * Depois de carregar os CSVs, rode o bloco "APÓS A CARGA" no fim do arquivo para
--     avançar os contadores IDENTITY além do maior valor carregado.
--
-- Data Modeler: para as colunas virem como tipo Lógico (e não Domínio), desmarque
--   "Create domains during import" em Preferências > Data Modeler > DDL antes de importar.
--
-- Ordem do script
--   1. Cada tabela: DROP TABLE ... CASCADE CONSTRAINTS seguido do CREATE TABLE
--      (dimensões em ordem alfabética, depois fatos e agregado). Na primeira execução,
--      os DROP retornam ORA-00942 (tabela não existe); é esperado e pode ser ignorado.
--   2. Chaves estrangeiras (ALTER TABLE ... ADD CONSTRAINT), criadas depois de todas as
--      tabelas, porque a ordem alfabética cria algumas tabelas antes das que elas referenciam.
--   3. Índices nas chaves estrangeiras.
--   4. Bloco comentado "APÓS A CARGA" para os contadores IDENTITY.
--   A dimensão de tempo se chama DIM_TEMPO no banco; o arquivo do pipeline é dim_data.csv
--   e a chave continua sk_data (data no formato AAAAMMDD).
-- =============================================================================


-- -----------------------------------------------------------------------------
-- DIMENSÕES (em ordem alfabética). Hierarquias Snowflake: tema -> assunto -> serviço; zona -> subprefeitura -> distrito; distrito -> estação do INMET
