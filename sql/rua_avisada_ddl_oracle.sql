DROP TABLE DIM_ASSUNTO CASCADE CONSTRAINTS;

CREATE TABLE DIM_ASSUNTO (
    sk_assunto  NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nm_assunto  VARCHAR2(200) NOT NULL,
    sk_tema     NUMBER(6) NOT NULL,
    CONSTRAINT PK_DIM_ASSUNTO PRIMARY KEY (sk_assunto)
);

COMMENT ON TABLE DIM_ASSUNTO IS 'Assunto do SP156; cada assunto pertence a um tema.';
COMMENT ON COLUMN DIM_ASSUNTO.sk_assunto IS 'Chave substituta sequencial do assunto (IDENTITY; na carga, recebe o valor do ETL).';
COMMENT ON COLUMN DIM_ASSUNTO.nm_assunto IS 'Nome do assunto como aparece no SP156.';
COMMENT ON COLUMN DIM_ASSUNTO.sk_tema IS 'FK para DIM_TEMA: tema ao qual o assunto pertence.';

