COMMENT ON TABLE DIM_STATUS IS 'Status do chamado no SP156 (Finalizada, Aberto, Em Andamento, Cancelada).';
COMMENT ON COLUMN DIM_STATUS.sk_status IS 'Chave substituta sequencial do status (IDENTITY; na carga, recebe o valor do ETL).';
COMMENT ON COLUMN DIM_STATUS.nm_status IS 'Status como aparece no SP156.';
COMMENT ON COLUMN DIM_STATUS.ds_grupo_status IS 'Agrupamento usado nos indicadores: finalizado, pendente (Aberto e Em Andamento) ou cancelado. (CSV: grupo_status)';

DROP TABLE DIM_SUBPREFEITURA CASCADE CONSTRAINTS;

CREATE TABLE DIM_SUBPREFEITURA (
    sk_subprefeitura  NUMBER(4) NOT NULL,
    nm_subprefeitura  VARCHAR2(60) NOT NULL,
