COMMENT ON COLUMN DIM_TEMPO.nr_ano IS 'Ano (ex.: 2026). (CSV: ano)';
COMMENT ON COLUMN DIM_TEMPO.nr_mes IS 'Mês de 1 a 12. (CSV: mes)';
