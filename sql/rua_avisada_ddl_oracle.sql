    sg_distrito              VARCHAR2(5),
    sk_subprefeitura         NUMBER(4) NOT NULL,
    ds_regiao_8              VARCHAR2(20),
    vl_area_km2              NUMBER(9,3) NOT NULL,
    qt_populacao             NUMBER(9) NOT NULL,
    qt_pop_60_mais           NUMBER(9) NOT NULL,
    pc_idosos                NUMBER(5,2),
    vl_densidade_hab_km2     NUMBER(9,1),
    vl_altitude_media_m      NUMBER(7,1),
    vl_amplitude_altitude_m  NUMBER(7,1),
    pc_declividade_media     NUMBER(6,2),
    pc_area_plana            NUMBER(5,2),
    vl_densidade_corregos    NUMBER(7,2),
    pc_area_perto_corrego    NUMBER(5,2),
    nr_indice_propensao      NUMBER(5,1),
    sk_estacao_inmet         NUMBER(4) NOT NULL,
    vl_distancia_estacao_km  NUMBER(6,1),
    CONSTRAINT PK_DIM_DISTRITO PRIMARY KEY (sk_distrito),
    CONSTRAINT CK_DISTRITO_PROPENSAO CHECK (nr_indice_propensao BETWEEN 0 AND 100)
);

COMMENT ON TABLE DIM_DISTRITO IS 'Os 96 distritos de São Paulo (GeoSampa), com população do Censo 2022, relevo (TOPODATA/INPE), córregos (Rede de Drenagem do GeoSampa) e o índice de propensão.';
COMMENT ON COLUMN DIM_DISTRITO.sk_distrito IS 'Código oficial do distrito no GeoSampa, 1 a 96 (chave natural, sem IDENTITY).';
COMMENT ON COLUMN DIM_DISTRITO.nm_distrito IS 'Nome do distrito em maiúsculas, sem acento (ex.: JARDIM HELENA).';
COMMENT ON COLUMN DIM_DISTRITO.sg_distrito IS 'Sigla do distrito no GeoSampa.';
COMMENT ON COLUMN DIM_DISTRITO.sk_subprefeitura IS 'FK para DIM_SUBPREFEITURA: subprefeitura que contém o distrito.';
COMMENT ON COLUMN DIM_DISTRITO.ds_regiao_8 IS 'Região em 8 grupos do GeoSampa (Leste 1, Leste 2, Norte 1, ...). (CSV: regiao_8)';
COMMENT ON COLUMN DIM_DISTRITO.vl_area_km2 IS 'Área do distrito em km², calculada do polígono (SIRGAS 2000 / UTM 23S). (CSV: area_km2)';
COMMENT ON COLUMN DIM_DISTRITO.qt_populacao IS 'População residente no Censo 2022 (IBGE, via TabNet da SMS-SP). (CSV: populacao)';
COMMENT ON COLUMN DIM_DISTRITO.qt_pop_60_mais IS 'Moradores com 60 anos ou mais no Censo 2022. (CSV: pop_60_mais)';
COMMENT ON COLUMN DIM_DISTRITO.pc_idosos IS 'Percentual de moradores com 60 anos ou mais. (CSV: pct_idosos)';
COMMENT ON COLUMN DIM_DISTRITO.vl_densidade_hab_km2 IS 'Habitantes por km². (CSV: densidade_hab_km2)';
COMMENT ON COLUMN DIM_DISTRITO.vl_altitude_media_m IS 'Altitude média do distrito em metros (TOPODATA, 30 m). (CSV: altitude_media_m)';
COMMENT ON COLUMN DIM_DISTRITO.vl_amplitude_altitude_m IS 'Diferença entre os percentis 95 e 5 da altitude do distrito, em metros. (CSV: amplitude_altitude_m)';
COMMENT ON COLUMN DIM_DISTRITO.pc_declividade_media IS 'Declividade média do terreno em % (TOPODATA). (CSV: declividade_media_pct)';
COMMENT ON COLUMN DIM_DISTRITO.pc_area_plana IS 'Percentual da área com declividade abaixo de 2% (onde a água tende a acumular). (CSV: pct_area_plana)';
COMMENT ON COLUMN DIM_DISTRITO.vl_densidade_corregos IS 'Quilômetros de córrego por km² de área (Rede de Drenagem do GeoSampa, sem trechos em lago ou represa). (CSV: densidade_corregos_km_km2)';
COMMENT ON COLUMN DIM_DISTRITO.pc_area_perto_corrego IS 'Percentual da área a até 200 m de um córrego. (CSV: pct_area_perto_corrego)';
COMMENT ON COLUMN DIM_DISTRITO.nr_indice_propensao IS 'Índice de propensão do terreno a alagar (0 a 100): média das posições relativas em área plana, declividade, altitude e proximidade de córrego. (CSV: indice_propensao)';
COMMENT ON COLUMN DIM_DISTRITO.sk_estacao_inmet IS 'FK para DIM_ESTACAO_INMET: estação mais próxima, cuja chuva é atribuída ao distrito.';
COMMENT ON COLUMN DIM_DISTRITO.vl_distancia_estacao_km IS 'Distância em km entre o distrito e a estação do INMET ligada a ele. (CSV: distancia_estacao_km)';

