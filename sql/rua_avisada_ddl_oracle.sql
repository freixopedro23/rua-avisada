-- -----------------------------------------------------------------------------
-- FATO 1: FTO_SOLICITACAO (grão = 1 chamado de drenagem do SP156)
-- -----------------------------------------------------------------------------

DROP TABLE FTO_SOLICITACAO CASCADE CONSTRAINTS;

CREATE TABLE FTO_SOLICITACAO (
    id_solicitacao         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    sk_data_abertura       NUMBER(8) NOT NULL,
    sk_data_finalizacao    NUMBER(8),
    sk_distrito            NUMBER(4),
    sk_servico             NUMBER(6) NOT NULL,
    sk_status              NUMBER(4) NOT NULL,
    qt_dias_ate_conclusao  NUMBER(5),
    fl_finalizado          NUMBER(1) NOT NULL,
    fl_conclusao_invalida  NUMBER(1) NOT NULL,
    qt_solicitacao         NUMBER(1) DEFAULT 1 NOT NULL,
    ds_origem_distrito     VARCHAR2(20) NOT NULL,
    ds_logradouro          VARCHAR2(200),
    nr_latitude            NUMBER(10,6),
    nr_longitude           NUMBER(10,6),
    CONSTRAINT PK_FTO_SOLICITACAO PRIMARY KEY (id_solicitacao),
    CONSTRAINT CK_SOL_FL_FINALIZADO CHECK (fl_finalizado IN (0, 1)),
    CONSTRAINT CK_SOL_FL_INVALIDA CHECK (fl_conclusao_invalida IN (0, 1)),
    CONSTRAINT CK_SOL_DIAS CHECK (qt_dias_ate_conclusao >= 0),
    CONSTRAINT CK_SOL_ORIGEM CHECK (ds_origem_distrito IN ('campo_distrito', 'coordenada', 'sem_distrito'))
);

COMMENT ON TABLE FTO_SOLICITACAO IS 'Fato de chamados: 1 linha por chamado de drenagem do SP156 aberto na temporada out/2025–mar/2026 (25.647 linhas). Número do imóvel e CEP foram descartados (LGPD).';
COMMENT ON COLUMN FTO_SOLICITACAO.id_solicitacao IS 'Identificador sequencial do chamado (IDENTITY; o CSV público não traz o protocolo; na carga, recebe o valor do ETL).';
COMMENT ON COLUMN FTO_SOLICITACAO.sk_data_abertura IS 'FK para DIM_TEMPO: dia de abertura do chamado.';
COMMENT ON COLUMN FTO_SOLICITACAO.sk_data_finalizacao IS 'FK para DIM_TEMPO: dia de finalização; vazio se o chamado não está finalizado.';
COMMENT ON COLUMN FTO_SOLICITACAO.sk_distrito IS 'FK para DIM_DISTRITO; vazio nos 10 chamados sem distrito identificável.';
COMMENT ON COLUMN FTO_SOLICITACAO.sk_servico IS 'FK para DIM_SERVICO: serviço solicitado.';
COMMENT ON COLUMN FTO_SOLICITACAO.sk_status IS 'FK para DIM_STATUS: status na data da extração (~ago/2026).';
COMMENT ON COLUMN FTO_SOLICITACAO.qt_dias_ate_conclusao IS 'Medida: dias entre abertura e finalização (só para finalizados). (CSV: dias_ate_conclusao)';
COMMENT ON COLUMN FTO_SOLICITACAO.fl_finalizado IS 'Medida: 1 se o chamado está finalizado, 0 caso contrário. (CSV: flag_finalizado)';
COMMENT ON COLUMN FTO_SOLICITACAO.fl_conclusao_invalida IS 'Medida de qualidade: 1 se a data de finalização era anterior à abertura (data descartada). (CSV: flag_conclusao_invalida)';
COMMENT ON COLUMN FTO_SOLICITACAO.qt_solicitacao IS 'Medida: contador de chamados (sempre 1), para somas. (CSV: qtd)';
COMMENT ON COLUMN FTO_SOLICITACAO.ds_origem_distrito IS 'Como o distrito foi definido: campo_distrito (nome no SP156), coordenada (junção espacial) ou sem_distrito. (CSV: origem_distrito)';
COMMENT ON COLUMN FTO_SOLICITACAO.ds_logradouro IS 'Nome da rua do chamado (sem número), usado no aviso por rua. (CSV: logradouro)';
COMMENT ON COLUMN FTO_SOLICITACAO.nr_latitude IS 'Latitude do chamado (WGS84), quando válida e dentro do município. (CSV: latitude)';
COMMENT ON COLUMN FTO_SOLICITACAO.nr_longitude IS 'Longitude do chamado (WGS84), quando válida e dentro do município. (CSV: longitude)';


