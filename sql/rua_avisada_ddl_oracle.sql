COMMENT ON COLUMN DIM_ESTACAO_INMET.sk_estacao_inmet IS 'Chave substituta sequencial da estação (IDENTITY; na carga, recebe o valor do ETL).';
COMMENT ON COLUMN DIM_ESTACAO_INMET.cd_wmo IS 'Código da estação no INMET (ex.: A701).';
COMMENT ON COLUMN DIM_ESTACAO_INMET.nm_estacao IS 'Nome da estação no INMET.';
COMMENT ON COLUMN DIM_ESTACAO_INMET.nr_latitude IS 'Latitude da estação (graus, WGS84). (CSV: latitude)';
COMMENT ON COLUMN DIM_ESTACAO_INMET.nr_longitude IS 'Longitude da estação (graus, WGS84). (CSV: longitude)';
COMMENT ON COLUMN DIM_ESTACAO_INMET.vl_altitude_m IS 'Altitude da estação em metros. (CSV: altitude_m)';

DROP TABLE DIM_SERVICO CASCADE CONSTRAINTS;

CREATE TABLE DIM_SERVICO (
    sk_servico             NUMBER(6) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nm_servico             VARCHAR2(200) NOT NULL,
    ds_categoria_drenagem  VARCHAR2(30) NOT NULL,
    sk_assunto             NUMBER(6) NOT NULL,
    CONSTRAINT PK_DIM_SERVICO PRIMARY KEY (sk_servico),
    CONSTRAINT CK_DIM_SERVICO_CAT CHECK (ds_categoria_drenagem IN ('manutencao', 'alagamento_cidadao'))
);

COMMENT ON TABLE DIM_SERVICO IS 'Serviços de drenagem do SP156 considerados no projeto; cada serviço pertence a um assunto.';
COMMENT ON COLUMN DIM_SERVICO.sk_servico IS 'Chave substituta sequencial do serviço, uma por combinação tema + assunto + serviço (IDENTITY; na carga, recebe o valor do ETL).';
COMMENT ON COLUMN DIM_SERVICO.nm_servico IS 'Nome do serviço como aparece no SP156 (ex.: Solicitar limpeza de bueiros, boca de lobo e poços de visita).';
COMMENT ON COLUMN DIM_SERVICO.ds_categoria_drenagem IS 'manutencao = pedido de limpeza ou conserto (entra no backlog); alagamento_cidadao = reclamação de alagamento feita pelo morador. (CSV: categoria_drenagem)';
COMMENT ON COLUMN DIM_SERVICO.sk_assunto IS 'FK para DIM_ASSUNTO: assunto ao qual o serviço pertence.';

DROP TABLE DIM_STATUS CASCADE CONSTRAINTS;

CREATE TABLE DIM_STATUS (
    sk_status        NUMBER(4) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    nm_status        VARCHAR2(40) NOT NULL,
    ds_grupo_status  VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_DIM_STATUS PRIMARY KEY (sk_status),
    CONSTRAINT CK_DIM_STATUS_GRUPO CHECK (ds_grupo_status IN ('finalizado', 'pendente', 'cancelado', 'outro'))
